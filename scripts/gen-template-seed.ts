/**
 * Writes supabase/migrations/20261013000200_template_registry_seed.sql from the
 * built catalog (run after `npm run templates:build`; re-run and apply when a
 * template is added or its version changes).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { templateFieldKeys, type Catalog, type FieldRegistry } from '@acad/engine';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'templates/dist/catalog.json'), 'utf8')) as Catalog;
const registry = JSON.parse(readFileSync(join(root, 'templates/fields.json'), 'utf8')) as FieldRegistry;
const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);

const rows = catalog.templates.map(({ definition: d, layout: l }) => {
  const fields = JSON.stringify(templateFieldKeys({ definition: d, layout: l }, registry).sort());
  return `  (${q(d.key)}, ${q(d.name)}, ${q(d.nameAr)}, ${d.version}, ${q(d.status)}, ${q(d.format)}, ${q(l.sourceSha256)}, ${q(l.baseSha256)}, ${l.pageCount}, ${q(fields)}::jsonb)`;
});
const sql = `-- Generated by scripts/gen-template-seed.ts — do not edit by hand.
insert into public.template_registry
  (template_key, name, name_ar, template_version, status, format, source_sha256, base_sha256, page_count, required_fields)
values
${rows.join(',\n')}
on conflict (template_key) do update set
  name = excluded.name,
  name_ar = excluded.name_ar,
  template_version = excluded.template_version,
  status = excluded.status,
  format = excluded.format,
  source_sha256 = excluded.source_sha256,
  base_sha256 = excluded.base_sha256,
  page_count = excluded.page_count,
  required_fields = excluded.required_fields,
  updated_at = now();
`;
writeFileSync(join(root, 'supabase/migrations/20261013000200_template_registry_seed.sql'), sql);
console.log(`template_registry seed: ${rows.length} templates`);
