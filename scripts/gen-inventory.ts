/** Writes docs/template-inventory.md from the template definitions (no historical values). */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getField, itemFields, type FieldRegistry, type MappingItem } from '@acad/engine';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(join(root, 'templates/fields.json'), 'utf8')) as FieldRegistry;
const defs = readdirSync(join(root, 'templates/definitions'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(join(root, 'templates/definitions', f), 'utf8')));
const layouts = Object.fromEntries(defs.map((d) => [d.key, JSON.parse(readFileSync(join(root, 'templates/dist', `${d.key}.layout.json`), 'utf8'))]));

const OPS: Record<string, string> = {
  date_field: 'auto-updating DATE field removed (fixed date printed instead)',
  insert_after: 'date position marked after the "التاريخ:" label',
  cell: 'historical table-cell value cleared',
  cell_containing: 'applicant name cell cleared (now printed from configuration)',
  text: 'historical phrase inside a sentence removed',
  replace_all: 'pre-ticked check box reset',
  remove_image: 'stamp / signature image removed',
  photo_grid: 'photo cards re-anchored; details/notes cells cleared',
  unfloat_nested_tables: 'floating tables anchored inline',
  redact_spans: 'typed-in historical values (Fill & Sign text) redacted',
  redact_text_rect: 'historical text redacted',
  remove_line_art: 'hand-placed tick marks removed',
  flatten_form: 'form fields reset and flattened (radio selections cleared)',
};

function describe(item: MappingItem): string {
  const keys = itemFields(item, registry);
  const label = (k: string) => getField(registry, k)?.label ?? k;
  if ('check' in item) return `☑ ${label(item.check.field)} = ${item.check.option ?? item.check.equals}`;
  if ('stamp' in item) return `stamp & signature (optional, ${item.stamp.size}pt wide)`;
  if ('photo' in item) return `photo #${item.photo.index + 1}`;
  if ('photoText' in item) return `photo #${item.photoText.index + 1} ${item.photoText.prop === 'details_ar' ? 'details' : 'notes'} (AR)`;
  if ('en' in item) return `EN: ${item.en.startsWith('$') ? 'company name (EN)' : item.en.startsWith('@') ? item.en.slice(1) : label(item.en)} · AR: ${item.ar.startsWith('$') ? 'company name (AR)' : item.ar.startsWith('@') ? item.ar.slice(1) : label(item.ar)}`;
  const v = item.value;
  if (v.startsWith('$')) return v.includes('_ar') ? 'company name (AR)' : 'company name (EN)';
  if (v.startsWith('@')) return `${v.slice(1)} (derived)`;
  if (v.includes('?')) return `${keys.map(label).join(' / ')} (conditional)`;
  return keys.map(label).join(', ');
}

let md = `# Template inventory\n\nGenerated by \`npx tsx scripts/gen-inventory.ts\` from \`templates/definitions/*.json\`. Historical values found in the originals are **not** listed here (the QA tooling re-derives them locally into the git-ignored \`templates/.qa/\`).\n\n`;
md += `**${defs.length} reference documents** (${defs.filter((d) => d.format === 'pdf').length} native PDF forms, ${defs.filter((d) => d.format === 'docx').length} Word documents). All are \`${[...new Set(defs.map((d) => d.status))].join(', ')}\`.\n\n`;
md += `| # | Template key | Source file | Format | Pages | Slots | Mapped items |\n| --- | --- | --- | --- | --- | --- | --- |\n`;
defs.forEach((d, i) => {
  md += `| ${i + 1} | \`${d.key}\` | ${d.source} | ${d.format.toUpperCase()} | ${layouts[d.key].pageCount} | ${Object.keys(layouts[d.key].slots).length} | ${d.fields.length} |\n`;
});
for (const d of defs) {
  md += `\n## ${d.name}\n\n- **Arabic title:** ${d.nameAr}\n- **Key / version:** \`${d.key}\` v${d.version} — status \`${d.status}\`\n- **Source:** \`reference-documents/${d.source}\` (${d.format.toUpperCase()}, ${layouts[d.key].pageCount} page(s))\n`;
  md += `- **Processing:** ${d.format === 'docx' ? 'sanitized DOCX copy → LibreOffice PDF base (OFL font substitutes) → slot geometry from invisible markers → browser overlay' : 'sanitized original PDF (true redaction / object removal) → fixed slot rectangles → browser overlay'}\n`;
  md += `- **Purpose:** ${d.description}\n`;
  if (d.reviewNotes) md += `- **Notes:** ${d.reviewNotes}\n`;
  const ops = d.sanitize === 'private' ? ['private operations (they name historical client values, kept with the private originals)'] : [...new Set(d.sanitize.map((o: { op: string }) => OPS[o.op] ?? o.op))];
  md += `- **Sanitization:** ${ops.join('; ')}; document metadata scrubbed.\n`;
  md += d.fields.some((f: MappingItem) => 'stamp' in f)
    ? `- **Signature / stamp areas:** the ACAD stamp & signature (uploaded privately in Settings) can optionally be placed on the consultant signature area.\n\n`
    : `- **Signature / stamp areas:** left blank for manual signing (no ACAD signature place).\n\n`;
  const ar: string[] = [];
  const en: string[] = [];
  const other: string[] = [];
  for (const item of d.fields as MappingItem[]) {
    const text = `\`${item.slot}\` → ${describe(item)}`;
    if ('en' in item) other.push(text);
    else if ('value' in item && (item.value.endsWith('_en') || item.value === '$consultant_name_en' || item.slot.endsWith('_en'))) en.push(text);
    else if ('value' in item && (item.value.endsWith('_ar') || item.slot.endsWith('_ar') || (item.dir === 'rtl'))) ar.push(text);
    else other.push(text);
  }
  if (ar.length) md += `**Arabic placements**\n\n${ar.map((x) => `- ${x}`).join('\n')}\n\n`;
  if (en.length) md += `**English placements**\n\n${en.map((x) => `- ${x}`).join('\n')}\n\n`;
  if (other.length) md += `**Bilingual / shared / marks**\n\n${other.map((x) => `- ${x}`).join('\n')}\n\n`;
}
writeFileSync(join(root, 'docs/template-inventory.md'), md);
console.log('docs/template-inventory.md written');
